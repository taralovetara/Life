def guiren_relation(guiren_gong, querent_gong):
    """
    判斷貴人宮與求測人宮之間的五行關係
    返回 (關係名稱, 等級1-5)
    """
    if guiren_gong == querent_gong:
        return ('同宮', 1)

    gwx = PALACE_WX[guiren_gong]
    qwx = PALACE_WX[querent_gong]

    if gwx == qwx:
        return ('比和', 2)
    elif WUXING_SHENG.get(gwx) == qwx:
        # 貴人生求測人 -> 等級2
        return ('貴人生我', 2)
    elif WUXING_SHENG.get(qwx) == gwx:
        # 求測人生貴人 -> 等級5
        return ('我生貴人', 5)
    elif WUXING_KE.get(gwx) == qwx:
        # 貴人剋求測人 -> 等級4
        return ('貴人剋我', 4)
    elif WUXING_KE.get(qwx) == gwx:
        # 求測人剋貴人 -> 等級3
        return ('我剋貴人', 3)

    return ('未知', 0)

