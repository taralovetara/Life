# 量化函數
def wx_relation(wx_a, wx_b):
    """返回 A 對 B 的五行關係"""
    if wx_a == wx_b: return '比和'
    if WUXING_SHENG.get(wx_a) == wx_b: return '生'
    if WUXING_KE.get(wx_a) == wx_b: return '剋'
    if WUXING_SHENG.get(wx_b) == wx_a: return '被生'
    if WUXING_KE.get(wx_b) == wx_a: return '被剋'
    return '未知'

RELATION_SCORE = {
    '生': +1.5,   # A生B，A付出
    '被生': +1.5, # B生A，A得利
    '剋': -2.0,   # A剋B，A壓制B
    '被剋': -2.0, # B剋A，A受制
    '比和': +0.5, # 平等和諧
}

