def find_parents(nianming):
    """根據年命推算父母用神"""
    wx_self = WUXING_TG[nianming]
    yy_self = YANG_YIN[nianming]
    # 生我者: 反推五行
    sheng_map = {'木':'水','火':'木','土':'火','金':'土','水':'金'}
    parent_wx = sheng_map[wx_self]
    parents = []
    for tg in TIAN_GAN:
        if WUXING_TG[tg] == parent_wx:
            if YANG_YIN[tg] == yy_self:
                parents.append((tg, '母親'))
            else:
                parents.append((tg, '父親'))
    return parents

